package sec07.exam01;

//------------------------
// 부모 클래스: Tire
//------------------------
class Tire {
	
	// 생성자를 직접 작성하지 않았다.
	// 이 경우 컴파일러가 기본 생성자 public Tire() {} 를 자동으로 만들어 준다.
	// 아래에서 new Tire() 를 호출할 수 있는 이유가 이 기본 생성자 덕분이다.
	
	// 일반 메소드: 자식 쪽에서 오버라이딩 하지 않으면 이 내용이 상속되어 실행된다.
	public void roll() {
		
		System.out.println("일반 타이어가 굴러갑니다.");
	}
}

//-------------------------------------------
// Car 클래스: 익명 자식 객체를 3가지 위치에서 사용해본다.
//-------------------------------------------
class Car {
	
	//==================
	//[비교용] 일반 객체 생성
	//==================
	// Tire 클래스로 평범하게 객체를 만들어 주소를 저장한다.
	// tire1.roll(); 을 호출하면 부모 Tire 의 원본 roll() 이 실행된다.
	private Tire tire1 = new Tire();
	
	//=====================================
	// 사용 위치1: 인스턴스 변수에 익명 자식 객체 저장
	//=====================================
	private Tire tire2 = new Tire() {
		
		// 부모 Tire 클래스에 만들어 놓은 roll() 을 메소드 오버라이딩(재정의) 한다.
		@Override
		public void roll() {
			
			System.out.println("익명 자식 클래스의 익명 객체1 타이어가 굴러갑니다.");
		}
	};
	
	//===================================================================================
	// run1() 메소드: 위 두 인스턴스 변수 tire1, tire2 에 저장된 각 객체의 roll() 을 호출해 차이를 확인한다.
	//===================================================================================
	public void run1() {
		
		//1. tire1 인스턴스 변수에 저장된 new Tire(); 객체의 roll() 메소드 호출해서 실행!
		this.tire1.roll(); // -> 부모 원본 roll() 실행: "일반 타이어가 굴러갑니다."
		
		//2. tire2 인스턴스 변수에 저장된 이름이 없는 익명 자식 객체의 메소드 오버라이딩 시켜놓은 roll() 메소드 호출해서 실행!
		this.tire2.roll(); // -> 메소드 오버라이딩 된 roll() 실행: "익명 자식 클래스의 익명 객체1 타이어가 굴러갑니다."
	}
	
	//=============================================
	// 사용 위치2: 메소드 안 지역 변수에 익명 자식 객체 저장
	//---------------------------------------------
	// 익명 자식 객체는 메소드 내부의 지역 변수에도 저장할 수 있다.
	// 이 객체는 run2() 실행 중에만 사용된다.
	//=============================================
	public void run2() {
		
		Tire tire = new Tire() {
			
			@Override
			public void roll() {// roll() 메소드 오버라이딩
				
				System.out.println("익명 자식 클래스의 익명 자식 객체 2의 타이어가 굴러갑니다.");
			}
		};
		
		// 익명 객체 내부에 포함한 메소드 오버라이딩 된 roll() 실행
		tire.roll();
	}// -- run2() 메소드 끝
	
	//=================================================
	// 사용 위치3: 매개변수로 익명 자식 객체 전달받기
	//-------------------------------------------------
	// 매개변수 자료형이 부모(Tire) 클래스 이므로,
	// 호출하는 쪽에서 익명 자식 객체를 만들어 매개변수로 전달할 수 있다.
	//=================================================
	public void run3(Tire tire) {
		
		// tire 매개변수에는 호출하는 쪽(main 메소드 쪽)에서 만들어 보낸 익명 자식 객체의 주소가 들어있다.
		// -> 그 익명 자식 객체 안의 오버라이딩 된 roll() 메소드가 실행된다.
		tire.roll();
	}
}// --- class Car 클래스 끝

public class CarExample {

	public static void main(String[] args) {
		
		// Car 클래스의 객체 생성(자동차 만들기)
		Car car = new Car();
		
		//-----------------------------------------------
		//[1] 인스턴스 tire1 과 tire2 에 저장된 익명 자식 객체 사용
		//-----------------------------------------------
		// 출력:
		// "일반 타이어가 굴러갑니다."
		// "익명 자식 클래스의 익명 객체1 타이어가 굴러갑니다."
		car.run1();
		
		//----------------------------------------------------
		//[2] run2() 메소드의 지역 변수 tire 에 저장된 익명 자식 객체 사용
		//----------------------------------------------------
		// 출력:
		// "익명 자식 클래스의 익명 자식 객체 2의 타이어가 굴러갑니다."
		car.run2();
		
		//------------------------------------------------------------
		//[3] run3(Tire tire) 메소드의 매개변수로 익명 자식 객체를 만들어 전달해 사용
		//------------------------------------------------------------
		// 출력:
		// "Tire 부모 클래스의 익명 자식 객체 3의 타이어가 굴러갑니다."
		car.run3(new Tire() {
			
			@Override
			public void roll() {
				
				System.out.println("Tire 부모 클래스의 익명 자식 객체 3의 타이어가 굴러갑니다.");
			}
		});
	}// -- main() 메소드 끝

}// --- class CarExample 클래스 끝



		String heightInput = "180"; // 입력받은 데이터가? 숫자로 구성된 문자열임
		// String weightInput = "75kg"; -> 입력받은 데이터가? 숫자 + k, g 문자 혼합되어 숫자로만 구성되지 않은 문자열임

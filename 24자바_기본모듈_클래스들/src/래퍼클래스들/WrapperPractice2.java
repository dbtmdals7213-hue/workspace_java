package 래퍼클래스들;

/*
	=============================================================================
	HealthInfoEntity(DB 에 저장되는 정보 구조)
		- DB 테이블의 한 줄(Row) 라고 보면 됨
		- 사용자가 입력한 값이 실제 DB 컬럼에 들어가기 전에 이 HealthInfoEntity 클래스의 객체에 담김
	=============================================================================
*/
class HealthInfoEntity {// <- DTO 역할을 하는 클래스
	
	//----------------------------
	// 실제 DB 의 컬럼에 저장될 값의 변수들
	//----------------------------
	Integer age; // 사용자의 나이(문자열 -> 숫자로 변환된 최종 값 저장)
	Integer height; // 사용자의 키(cm 단위, 숫자로 변환된 최종 값 저장)
	Integer weight; // 사용자의 몸무게(kg 단위, 숫자로 변환된 최종 값 저장)
	Double bmi; // BMI 계산 결과(키와 몸무게가 정상일 때 계산됨)
	
	//--------------------------------------------------
	// 생성자 - 객체를 생성할 때 필요한 값들을 한 번에 저장(초기화) 가능
	// new HealthInfoEntity(값들, ...) 형태로 사용됨
	//--------------------------------------------------
	public HealthInfoEntity(Integer age, Integer height, Integer weight, Double bmi) {
		super();
		this.age = age;
		this.height = height;
		this.weight = weight;
		this.bmi = bmi;
	}
	
	//---------------------------------------
	// DB 에 저장되어 있다고 가정하고, 데이터를 확인 출력
	//---------------------------------------
	public void printData() {
		
		System.out.println("======= DB 저장 데이터 확인 =======");
		System.out.println("나이(age): " + this.age);
		System.out.println("키(height): " + this.height);
		System.out.println("몸무게(weight): " + this.weight);
		System.out.println("BMI 지수(bmi): " + this.bmi);
	}
	
}

/*
	===========================================================================
	HealthInfoService(DB 저장 흐름 담당)
		- Controller(웹 요청) -> Service(처리) -> Repository(DB) 구조 중 Service 역할
		- 여기서는 가짜로 DB 에 저장한다고 "시뮬레이션" 만 함(실무에 가까운 구조 훈련)
	===========================================================================
*/
class HealthInfoService {
	
	//-----------------------------------------------------------
	// isNumeric 메소드
	// - 매개변수로 전달받은 문자열(text)이 "숫자로만 이루어져 있는지" 확인하는 기능
	// - 문자, 한글, 기호, 공백, 단위(km, cm)가 섞이면 숫자가 아니라고 판단
	// - 입력한 검증(유효성 검사) 단계에서 매우 자주 사용됨
	//-----------------------------------------------------------
	public static boolean isNumeric(String text) {
		
		//-----------------------------------------------------------------------------
		//1) 가장 기본적으로 사용자가 아무것도 입력 안했을 경우, 스페이스바(공백)만 입력했을 경우 오류 / 예외 처리
		//-----------------------------------------------------------------------------
		if(text == null || text.trim().equals("")) {
			
			return false;
			// text == null -> 입력 자체가 안됬음
			// text.trim().equals("") -> " " 같은 공백 제거 후 빈 문자열이면? 숫자가 아님
		}// if 조건문
		
		//-------------------------------------------------------------------------------
		//2) 문자열 내부가 전부 숫자로 구성되어 있는지 한 글자씩 검사
		//		예)	사용자가 입력한 데이터 전체 문자열이 "123" 이면? String text 매개변수로 전달받을 것이다.
		//			"123" 을 -> ['1', '2', '3']
		//			"75KG" 을 -> ['7', '5', 'K', 'G']
		//-------------------------------------------------------------------------------
		//		   : ['1', '2', '3']
		for(char c : text.trim().toCharArray()) {
			
			// Character.isDigit(검사할문자)
			// -> 검사할 문자가 '0 ~ 9' 사이의 숫자인지 체크하는 메소드
			if(!Character.isDigit(c)) {
				
				return false; // 숫자로 구성된 문자가 아님이 발견된 즉시 false 반환
							  // 예) "25a" 입력받을 경우 -> 'a' 문자 검사하면 false 반환
							  // 예) "75KG" 입력받을 경우 -> 'K' 문자 검사하면 false 반환
			}// if 조건문
		}// for 반복문
		
		//3) 숫자로만 구성된 문자열을 입력 받았을 경우 예) "100", "25", "003", ... 입력 받았을 경우
		return true;
		
	}// === isNumeric 메소드
	
	public static Integer toInteger(String text) {
		
		//1) 먼저 매개변수 String text 로 전달받은 입력받은 문자열이 숫자로만 구성되어 있는 문자열인지
		if(isNumeric(text)) {// isNumeric(text) == treu 인 경우에만 다음 코드 진행
			
			//2) 실제 문자열을 숫자로 변환
			// - Integer.parseInt("100"); -> 100 정수로 변환해서 반환
			return Integer.parseInt(text.trim());
		}
		
		//3) 숫자 형태로 구성된 문자열이 아니라면? null 반환
		// - 즉, "25kg", "한글", null, "", ... 으로 입력 받았을 경우
		// - 오류(Exception)를 내지 않고 null 을 반환하는 이유
		//	 1. DB 의 테이블에 값이 비어 있어야 하는 경우(NULL 저장)
		//	 2. 계산할 수 없는 데이터는 제외 / 무시하도록 처리
		//	 3. 자바 프로그램이 멈추지 않게 안전하게 진행
		return null;
		// DB 의 테이블에 저장 시 "값 없음" 으로 처리됨(유효성 검증 단계에서 매우 중요)
	}// === toInteger 메소드
	
	public static Double calculateBMI(Integer height, Integer weight) {
		
		//1) 사용자가 키와 몸무게를 입력하지 않았을 경우 검사
		if(height == null || weight == null) {
			
			return null; // BMI 계산 불가능 -> 계산을 강제로 시도하면 오류가 나기 때문에 차단하도록 null 반환
		}
		//------------------------------------------------
		//2) BMI 공식에서 키는 "cm" 가 아니라 "미터(m)" 단위가 필요함
		// - height 가 180이라면 -> 180cm -> 1.80m 로 변환
		// - 그래서 100.0으로 나눠 소수점 계산이 되도록 double 사용
		//------------------------------------------------
		double meter = height / 100.0;
		//				  170 / 100.0 = 1.70
		//				  180 / 100.0 = 1.80
		
		//-----------------------------------------------
		//3) 비정상적인 입력 값 방지 조건
		// - meter <= 0 : 0m 또는 음수 단위는 존재할 수 없음
		// - weight <= 0 : 몸구게가 0 또는 음수일 수 없음
		// - 이런 값이 들어왔다면 계산 자체가 의미가 없으므로 null 반환
		//-----------------------------------------------
		if(meter <= 0 || weight <= 0) {
			
			return null; // 유효하지 않은 데이터 -> BMI 계산 중단을 위해 null 반환
		}
		
		//------------------------------------------
		//4) 정상 입력일 때만 BMI 계산 실시
		//		공식) BMI = 몸무게(kg) / (키(m) X 키(m))
		//------------------------------------------
		return weight / (meter * meter);
		// 예시) weight = 70kg , height = 1.75m 일 경우!
		// BMI = 70 / (1.75 * 1.75);
		//	   = 22.86 정상 범위
	}// === calculateBMI 메소드
	
	// DTO 역할을 하는 객체 반환
	public static HealthInfoEntity createHealthInfo(String ageInput, String heightInput, String weightInput) {
		
		//---------------------------------------------------------
		//1) 입력 값 전처리(trim + null) 체크
		//	 사용자가 입력한 값이 비어있거나(null), 공백이 포함될 수 있기 때문에
		//	 null 이면 그대로 null, 입력한 값이 있으면 앞, 뒤 공백 제거(trim())
		//---------------------------------------------------------
		ageInput = (ageInput == null) ? null : ageInput.trim(); // " 27 " -> "27"
		heightInput = (heightInput == null) ? null : heightInput.trim(); // "180 " -> "180"
		weightInput = (weightInput == null) ? null : weightInput.trim(); // "75kg " -> "75kg"

		//------------------------------------------------------------
		//2) 입력한 문자열 값을 안전하게 숫자로 변환
		// - "25" -> 25, "175" -> 175
		// - "70kg", "abc", null ->  변환 실패 -> null 반환
		// -> null 을 반환하는 이유: DB 에서 "아예 값이 없다(null)" 로 표현하기 위함
		//------------------------------------------------------------
		Integer age = toInteger(ageInput); // 입력받은 나이: 문자열에서 정수 변환 시도
		Integer height = toInteger(heightInput); // 입력받은 키: "180" -> 180 정수로 변환 시도
		Integer weight = toInteger(weightInput); // 입력받은 몸무게: "75kg" -> 정수로 변환 불가 -> null 반환 받아 저장
												 // 입력받은 몸무게: "75" -> 75 정수로 변환 시도
		
		//------------------------------------------------------------
		//3) BMI 계산
		// - height, weight 가 정상적으로 입력 되었을 때만 BMI 계산
		// - 하나라도 입력되어 있지 않다면(null 이면) -> BMI 도 null(계산 불가 의미)
		//------------------------------------------------------------
		Double bmi = calculateBMI(height, weight);
		
		//-------------------------------------------------------------------------------------------
		//4) DTO 역할을 하는 HealthInfoEntity 클래스의 객체를 생성해서 DB 의 테이블에 한 줄 추가
		// - 최종적으로 DB 의 테이플에 저장된 구조를 하나의 객체를 생성해서 만든다.
		// - 만든 하나의 DTO 역할을 하는 HealthInfoEntity 객체를 DB 의 테이블에 추가(insert) 했다고 가정하고 그 정보 출력
		//-------------------------------------------------------------------------------------------
		HealthInfoEntity dto = new HealthInfoEntity(age, height, weight, bmi); // <- DB 의 테이블에 저장된 하나의 레코드 정보
		
		//---------------------------------------------------------------------
		//5) DB 의 테이블에 하나의 레코드 형태로 바로 4) 에서 생성한 객체의 정보가 저장됬다고 가정하고
		//	 여기 이 자리에 정보들을 얻어서 출력해보자.
		//---------------------------------------------------------------------
		System.out.println("DB 저장 완료(가정) -> INSERT INTO 테이블명 VALUES(age, weight, bmi);");
		dto.printData(); // 실제 저장된 데이터 확인 용도(SELECT * FROM 테이블명 조회 결과를 보는 느낌)
		
		//--------------------------------------------------------------------------------------
		//6) Controller(사장) 에 돌려주는 반환 단계
		// - 컨트롤러(main 메소드)가 다시 웹 브라우저 화면(클라이언트가 브라우저로 요청한 화면)으로 응답(출력) 보낼 수 있도록
		// - HealthInfoService 서비스 클래스가 처리한 결과 DB 저장 완료한 HealthInfoEntity 객체 정보를 내보낸다.
		//--------------------------------------------------------------------------------------
		return dto;
	}// === createHealthInfo 메소드
	
}// --- HealthInfoService 클래스


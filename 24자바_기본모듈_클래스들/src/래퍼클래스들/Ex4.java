package 래퍼클래스들;

public class Ex4 {

	public static void main(String[] args) {
		
		//==================================================================
		// 박싱(수동 박싱) 방법1. new 연산자로 객체를 생성해서 기본 자료형 값 10을 저장하는 방법
		//==================================================================
		// Integer iValue1 = new Integer(10);
		// 위 코드의 의미: new 가 실행될 때 마다 JVM 의 Heap 에 "무조건" 새 Integer 객체를 만든다.
		// 그리고 그 객체의 주소를 JVM 의 Stack 에 있는 참조변수 iValue1 에 저장한다.
		
		// Integer iValue2 = new Integer(10);
		// 위 코드의 의미: 저장하려는 값이 똑같은 10이어도, new 는 또 새 객체를 만든다.
		// 결과:	저장하려는 기본 자료형 값 10은 같은데 객체는 2개. 
		//		즉, 같은 값 10이 JVM 의 Heap 에 객체 메모리를 2번 차지 한다.(메모리 낭비)
		
		//============================================================================
		// 박싱(수동 박싱) 방법2. static 메소드 valueOf() 메소드 사용
		// -> 핵심: "이미 같은 값이 저장된 래퍼 객체가 있으면, 그 객체를 재활용 한다."(이것을 캐싱이라 부른다)
		//============================================================================
		// Integer.valueOf(10); 10이 저장(박싱)된 Integer 객체의 주소를 반환한다.
		// 지금은 첫 호출이므로, JVM 의 Heap 영역에 Integer(10) 객체가 처음으로 1개 만들어진다.
		Integer iValue1 = Integer.valueOf(10);
		
		// 다시 valueOf(10); 호출: 값이 같은 10이므로 새 객체를 만들지 않는다.
		// 아까 만들어 둔 Integer(10) 객체의 주소만 그대로 반환합니다.
		Integer iValue2 = Integer.valueOf(10);
		
		if(iValue1 == iValue2) {// valueOf() 로 박싱했으므로 Integer 객체 주소가 같다 -> 이 문장이 출력된다.
			
			System.out.println("iValue1 참조변수와 iValue2 참조변수는 각각 동일한 하나의 래퍼 Integer 객체 메모리 사용");
		}else {// new 로 박싱했다면 Integer 객체 주소가 각각 달라서 이쪽이 출력되었을 것이다.
			
			System.out.println("iValue1 참조변수와 iValue2 참조변수는 각각 생성된 다른 래퍼 Integer 객체 메모리 사용");
		}
		
	}// === main 메소드

}// --- Ex4 클래스


